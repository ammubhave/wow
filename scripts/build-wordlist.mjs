// Builds the built-in sheet's word list (for =MATCHES, =ANAGRAMS and =ISWORD) from the
// Collaborative Word List (Crossword Nexus, MIT licensed): words and phrases, written without
// spaces as crosswords do (ICECREAMBAR), with a quality score from 0 to 100.
//
// Usage: node scripts/build-wordlist.mjs
//
// Writes public/wordlist/words-<hash>.txt.gz (one entry per line, best-scored first, so lookups
// list good fill before obscure entries), the list's license next to it, and
// src/components/sheet/wordlist-file.ts naming the file. The name changes with the contents, so
// browsers can cache it forever. Delete the old .txt.gz after regenerating.
import {createHash} from "node:crypto";
import {mkdirSync, writeFileSync} from "node:fs";
import {gzipSync} from "node:zlib";

// A fixed commit, so rebuilding gives the same list until this is bumped.
const COMMIT = "b51b2ad6876c1dc3f9df212e1ed8535fc9e4770a";
const BASE = `https://raw.githubusercontent.com/Crossword-Nexus/collaborative-word-list/${COMMIT}`;
// Scores below this mark entries the list's editors rejected (misspellings, slurs).
const MIN_SCORE = 5;

async function download(path) {
  const response = await fetch(`${BASE}/${path}`);
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  return response.text();
}

const [dict, license] = await Promise.all([download("xwordlist.dict"), download("LICENSE")]);

const best = new Map();
for (const line of dict.split("\n")) {
  const [raw, scoreText] = line.trim().split(";");
  const word = raw?.toUpperCase();
  const score = Number(scoreText);
  if (!word || !/^[A-Z]+$/.test(word) || !(score >= MIN_SCORE)) continue;
  best.set(word, Math.max(score, best.get(word) ?? 0));
}
const words = [...best]
  .toSorted(([a, x], [b, y]) => y - x || (a < b ? -1 : 1))
  .map(([word]) => word);

const gz = gzipSync(`${words.join("\n")}\n`, {level: 9});
const hash = createHash("sha256").update(gz).digest("hex").slice(0, 10);
const file = `words-${hash}.txt.gz`;

mkdirSync("public/wordlist", {recursive: true});
writeFileSync(`public/wordlist/${file}`, gz);
writeFileSync(
  "public/wordlist/LICENSE.txt",
  `The word list in this folder is derived from the Collaborative Word List\n(https://github.com/Crossword-Nexus/collaborative-word-list, commit ${COMMIT}).\n\n${license}`
);
writeFileSync(
  "src/components/sheet/wordlist-file.ts",
  `// Generated by scripts/build-wordlist.mjs: don't edit.\nexport const WORDLIST_URL = "/wordlist/${file}";\nexport const WORDLIST_ENTRIES = ${words.length};\n`
);
console.log(
  `${words.length} entries, ${(gz.length / 1e6).toFixed(2)} MB → public/wordlist/${file}`
);
